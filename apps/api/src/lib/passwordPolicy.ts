import { z } from "zod";

/** เพิ่มภายหลัง (audit fix — ความปลอดภัยรหัสผ่าน) — เดิมเช็คแค่ความยาว (min 8) ไม่มีเงื่อนไข
 *  ความซับซ้อนเลย ทำให้รหัสผ่านแบบ "aaaaaaaa" ผ่านได้ ใช้ policy มาตรฐานทั่วไป (คล้าย OWASP/NIST
 *  baseline): อย่างน้อย 8 ตัวอักษร (สูงสุด 72 ไบต์ตามข้อจำกัดของ bcrypt) ต้องมีตัวพิมพ์เล็ก
 *  ตัวพิมพ์ใหญ่ ตัวเลข และอักขระพิเศษ อย่างน้อยอย่างละ 1 ตัว — ใช้ร่วมกันทั้ง POST /auth/register
 *  และ POST /auth/password/reset (จุดเดียวที่รับรหัสผ่านใหม่จากผู้ใช้) */
export const passwordSchema = z
  .string()
  .min(8, "รหัสผ่านต้องมีอย่างน้อย 8 ตัวอักษร")
  .max(72, "รหัสผ่านต้องไม่เกิน 72 ตัวอักษร")
  .regex(/[a-z]/, "รหัสผ่านต้องมีตัวพิมพ์เล็กอย่างน้อย 1 ตัว")
  .regex(/[A-Z]/, "รหัสผ่านต้องมีตัวพิมพ์ใหญ่อย่างน้อย 1 ตัว")
  .regex(/[0-9]/, "รหัสผ่านต้องมีตัวเลขอย่างน้อย 1 ตัว")
  .regex(/[^A-Za-z0-9]/, "รหัสผ่านต้องมีอักขระพิเศษอย่างน้อย 1 ตัว (เช่น !@#$%^&*)");
